"""Owned syscall callback-body snapshots, with fixed maps and no task reads."""

from scheduler_dynamic_program import ACK, Program


def clock_program(storage, counts, records, capacity):
    if type(capacity) is not int or not 1 <= capacity <= 128:
        raise ValueError("unsupported fixed clock ledger capacity")
    p = Program()
    p.mov(6, 1)
    p.current_storage(storage)
    p.jump(0x15, "return", 0)
    p.emit(0x79, 1, 0)
    p.jump(0x55, "return", 1, imm=ACK)
    p.emit(0x79, 1, 6, 8)
    p.jump(0x55, "return", 1, imm=186)
    p.call(8)
    p.emit(0x63, 10, 0, -8)
    p.call(5)
    p.emit(0x7B, 10, 0, -16)
    p.array(counts, 0)
    p.jump(0x15, "return", 0)
    p.mov(9, 0)
    p.number(1, 1)
    p.emit(0xC3, 9, 1, imm=1)
    p.jump(0x35, "overflow", 1, imm=capacity)
    p.emit(0x63, 10, 1, -4)
    p.array(records)
    p.jump(0x15, "overflow", 0)
    p.mov(7, 0)
    p.emit(0x61, 1, 10, -4)
    p.emit(0x07, 1, imm=1)
    p.emit(0x63, 7, 1)
    p.emit(0x61, 1, 10, -8)
    p.emit(0x63, 7, 1, 4)
    p.emit(0x62, 7, off=12)
    p.emit(0x79, 1, 10, -16)
    p.emit(0x7B, 7, 1, 16)
    p.call(5)
    p.emit(0x7B, 7, 0, 24)
    p.call(8)
    p.emit(0x63, 7, 0, 8)
    p.jump(0x05, "return")
    p.label("overflow")
    p.number(1, 1)
    p.emit(0xC3, 9, 1, off=4)
    p.exit()
    return p.encode()
